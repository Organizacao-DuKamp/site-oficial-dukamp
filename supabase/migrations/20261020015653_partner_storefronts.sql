CREATE FUNCTION public.claim_partner_store_payment(p_store uuid,p_order uuid) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE o public.partner_store_orders%ROWTYPE;retry boolean;BEGIN
 SELECT * INTO o FROM public.partner_store_orders WHERE id=p_order AND store_id=p_store FOR UPDATE;
 IF NOT FOUND OR o.source<>'online' THEN RAISE EXCEPTION 'Pedido inválido';END IF;
 IF o.payment_id IS NOT NULL OR o.checkout_url IS NOT NULL OR o.payment_status='approved' THEN RETURN jsonb_build_object('claimed',false,'issued',true);END IF;
 IF o.payment_attempt_started_at>now()-interval '90 seconds' THEN RETURN jsonb_build_object('claimed',false,'issued',false);END IF;
 retry:=o.payment_attempt_started_at IS NOT NULL;
 UPDATE public.partner_store_orders SET payment_attempt_started_at=now() WHERE id=o.id;
 RETURN jsonb_build_object('claimed',true,'issued',false,'retry',retry);
END $$;
REVOKE ALL ON FUNCTION public.claim_partner_store_payment(uuid,uuid) FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.claim_partner_store_payment(uuid,uuid) TO service_role;
