 coalesce(sum(CASE WHEN o.partner_id IS NOT NULL THEN o.partner_gross_total ELSE o.subtotal+o.shipping_cost+coalesce(o.tax_amount,0) END) FILTER(WHERE o.payment_status='approved' AND o.delivery_status<>'cancelada' AND o.refund_status='none'),0) AS gross_total,
 coalesce(sum(o.partner_commission_amount+o.origin_commission_amount) FILTER(WHERE o.payment_status='approved' AND o.delivery_status<>'cancelada' AND o.refund_status='none'),0) AS commission_total,
 coalesce(sum(o.total) FILTER(WHERE o.payment_status='approved' AND o.delivery_status<>'cancelada' AND o.refund_status='none'),0) AS dukamp_total
 FROM public.dukamp_partners p LEFT JOIN public.orders o ON o.partner_id=p.id OR o.origin_partner_id=p.id GROUP BY p.id;
