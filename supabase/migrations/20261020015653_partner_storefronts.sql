CREATE FUNCTION public.cancel_unpaid_partner_store_order(p_store uuid,p_order uuid) RETURNS jsonb LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE o public.partner_store_orders%ROWTYPE;i jsonb;BEGIN
 SELECT * INTO o FROM public.partner_store_orders WHERE id=p_order AND store_id=p_store FOR UPDATE;
 IF NOT FOUND OR o.source<>'online' OR o.payment_status NOT IN('pending','rejected') OR o.expires_at>now()-interval '1 hour' THEN RAISE EXCEPTION 'Pedido ainda não pode ser cancelado';END IF;
 IF NOT o.stock_released THEN FOR i IN SELECT value FROM jsonb_array_elements(o.items) LOOP
 UPDATE public.partner_store_products SET stock=stock+(i->>'quantity')::int WHERE id=(i->>'product_id')::uuid AND store_id=p_store;END LOOP;END IF;
 UPDATE public.partner_store_orders SET stock_released=true,payment_status='cancelled',delivery_status='cancelado' WHERE id=o.id RETURNING * INTO o;RETURN to_jsonb(o);
END $$;
