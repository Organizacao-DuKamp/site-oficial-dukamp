-- Service-only tenant APIs validate the live partner identity on every request.
CREATE TABLE public.partner_stores (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), partner_id uuid NOT NULL UNIQUE REFERENCES public.dukamp_partners(id),
 slug text NOT NULL UNIQUE CHECK(slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$' AND length(slug) BETWEEN 3 AND 48),
 name text NOT NULL, published boolean NOT NULL DEFAULT false, config jsonb NOT NULL DEFAULT '{}' CHECK(jsonb_typeof(config)='object'),
 payment_connected boolean NOT NULL DEFAULT false, payment_account text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.partner_store_credentials (
 store_id uuid PRIMARY KEY REFERENCES public.partner_stores(id), encrypted_token text NOT NULL,
 encrypted_refresh text, collector_id text NOT NULL, expires_at timestamptz, connection_type text NOT NULL DEFAULT 'credentials', updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.partner_store_oauth_states (
 state_hash text PRIMARY KEY, store_id uuid NOT NULL REFERENCES public.partner_stores(id), user_id uuid NOT NULL REFERENCES auth.users(id),
 verifier text NOT NULL, expires_at timestamptz NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE public.partner_store_products (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(), store_id uuid NOT NULL REFERENCES public.partner_stores(id),
 name text NOT NULL,code text NOT NULL DEFAULT '',description text NOT NULL DEFAULT '',category text NOT NULL DEFAULT '',brand text NOT NULL DEFAULT '',unit text NOT NULL DEFAULT 'un',
 images jsonb NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(images)='array'),price numeric(12,2) NOT NULL CHECK(price>0),cost numeric(12,2) NOT NULL DEFAULT 0 CHECK(cost>=0),
 stock integer NOT NULL DEFAULT 0 CHECK(stock>=0),active boolean NOT NULL DEFAULT true,deleted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),UNIQUE(id,store_id)
);
CREATE INDEX partner_store_products_catalog ON public.partner_store_products(store_id,active,category);
CREATE TABLE public.partner_store_orders (
 id uuid PRIMARY KEY DEFAULT gen_random_uuid(),store_id uuid NOT NULL REFERENCES public.partner_stores(id),order_number bigint GENERATED BY DEFAULT AS IDENTITY,
 request_id uuid NOT NULL, request_hash text NOT NULL,access_hash text NOT NULL, customer jsonb NOT NULL, items jsonb NOT NULL CHECK(jsonb_array_length(items)>0),
 subtotal numeric(12,2) NOT NULL CHECK(subtotal>0),shipping_cost numeric(12,2) NOT NULL CHECK(shipping_cost>=0),total numeric(12,2) NOT NULL CHECK(total=subtotal+shipping_cost),
 fulfillment text NOT NULL CHECK(fulfillment IN('delivery','pickup')),payment_method text NOT NULL CHECK(payment_method IN('pix','card','manual')),
 payment_status text NOT NULL DEFAULT 'pending' CHECK(payment_status IN('pending','in_process','approved','rejected','cancelled','refunded','charged_back')),
 delivery_status text NOT NULL DEFAULT 'preparando' CHECK(delivery_status IN('preparando','enviado','entregue','cancelado')),
 source text NOT NULL CHECK(source IN('manual','online')),notes text NOT NULL DEFAULT '',payment_id text,provider_updated_at timestamptz,checkout_url text,qr_code text,qr_image text,
 stock_released boolean NOT NULL DEFAULT false, expires_at timestamptz NOT NULL DEFAULT now()+interval '30 minutes',deleted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),updated_at timestamptz NOT NULL DEFAULT now(),UNIQUE(store_id,request_id),UNIQUE(store_id,payment_id)
);
CREATE INDEX partner_store_orders_tenant ON public.partner_store_orders(store_id,created_at DESC);
CREATE TABLE public.partner_store_visits (store_id uuid NOT NULL REFERENCES public.partner_stores(id),day date NOT NULL DEFAULT current_date,visitor_hash text NOT NULL,PRIMARY KEY(store_id,day,visitor_hash));
CREATE TABLE public.partner_store_rate_limits (bucket text PRIMARY KEY,hits integer NOT NULL DEFAULT 1,expires_at timestamptz NOT NULL);
DO $$ DECLARE t text; BEGIN
 FOREACH t IN ARRAY ARRAY['partner_stores','partner_store_credentials','partner_store_oauth_states','partner_store_products','partner_store_orders','partner_store_visits','partner_store_rate_limits'] LOOP
  EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',t);
  EXECUTE format('REVOKE ALL ON public.%I FROM anon,authenticated',t);
  EXECUTE format('GRANT ALL ON public.%I TO service_role',t);
 END LOOP;
 FOREACH t IN ARRAY ARRAY['partner_stores','partner_store_products','partner_store_orders'] LOOP
  EXECUTE format('CREATE TRIGGER updated_at BEFORE UPDATE ON public.%I FOR EACH ROW EXECUTE FUNCTION public.tg_set_updated_at()',t);
 END LOOP;
END $$;
GRANT USAGE,SELECT ON SEQUENCE public.partner_store_orders_order_number_seq TO service_role;

CREATE FUNCTION public.partner_store_rate_limit(p_bucket text,p_limit integer) RETURNS boolean
 LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE n integer; BEGIN
 DELETE FROM public.partner_store_rate_limits WHERE expires_at<now();
 INSERT INTO public.partner_store_rate_limits(bucket,hits,expires_at) VALUES(p_bucket,1,now()+interval '1 minute')
 ON CONFLICT(bucket) DO UPDATE SET hits=public.partner_store_rate_limits.hits+1 RETURNING hits INTO n;
 RETURN n<=p_limit;
END $$;

CREATE FUNCTION public.create_partner_store_order(p_store uuid,p_request uuid,p_request_hash text,p_access_hash text,p_customer jsonb,p_items jsonb,p_fulfillment text,p_method text,p_source text) RETURNS jsonb
 LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE s public.partner_stores%ROWTYPE;o public.partner_store_orders%ROWTYPE;p public.partner_store_products%ROWTYPE; i record;
 lines jsonb:='[]';sub numeric:=0;freight numeric:=0;found_prefix boolean; BEGIN
 -- Serializes checkout idempotency and catalog edits for this store.
 SELECT * INTO s FROM public.partner_stores WHERE id=p_store FOR UPDATE;
 IF NOT FOUND OR NOT EXISTS(SELECT 1 FROM public.dukamp_partners WHERE id=s.partner_id AND active AND deleted_at IS NULL) THEN RAISE EXCEPTION 'Loja indisponível'; END IF;
 SELECT * INTO o FROM public.partner_store_orders WHERE store_id=s.id AND request_id=p_request;
 IF FOUND THEN
  IF o.request_hash<>p_request_hash OR o.access_hash<>p_access_hash THEN RAISE EXCEPTION 'Solicitação já utilizada para outro pedido'; END IF;
  RETURN to_jsonb(o);
 END IF;
 IF p_source NOT IN('online','manual') OR (p_source='online' AND (NOT s.published OR NOT s.payment_connected OR p_method='manual')) THEN RAISE EXCEPTION 'Checkout indisponível'; END IF;
 IF p_source='manual' AND p_method<>'manual' THEN RAISE EXCEPTION 'Forma de pagamento inválida'; END IF;
 IF jsonb_array_length(p_items)=0 OR jsonb_array_length(p_items)>100 THEN RAISE EXCEPTION 'Carrinho inválido'; END IF;
 FOR i IN SELECT (value->>'product_id')::uuid AS id,sum((value->>'quantity')::integer)::integer AS qty FROM jsonb_array_elements(p_items) GROUP BY 1 ORDER BY 1 LOOP
  SELECT * INTO p FROM public.partner_store_products WHERE id=i.id AND store_id=s.id AND active AND deleted_at IS NULL FOR UPDATE;
  IF NOT FOUND OR i.qty<=0 OR i.qty>10000 OR p.stock<i.qty THEN RAISE EXCEPTION 'Produto indisponível ou estoque insuficiente'; END IF;
  lines:=lines||jsonb_build_array(jsonb_build_object('product_id',p.id,'name',p.name,'unit_price',p.price,'quantity',i.qty,'subtotal',p.price*i.qty,'cost',p.cost));
  sub:=sub+p.price*i.qty;
  UPDATE public.partner_store_products SET stock=stock-i.qty WHERE id=p.id;
 END LOOP;
 IF p_fulfillment='pickup' THEN
  IF NOT coalesce((s.config->>'pickup_enabled')::boolean,true) THEN RAISE EXCEPTION 'Retirada indisponível'; END IF;
 ELSIF p_fulfillment='delivery' THEN
  SELECT EXISTS(SELECT 1 FROM jsonb_array_elements_text(coalesce(s.config->'delivery_cep_prefixes','[]')) x WHERE (p_customer->>'cep') LIKE x||'%') INTO found_prefix;
  IF NOT coalesce((s.config->>'delivery_enabled')::boolean,false) OR NOT found_prefix THEN RAISE EXCEPTION 'CEP fora da região de entrega'; END IF;
  freight:=coalesce((s.config->>'delivery_fee')::numeric,0);
  IF coalesce((s.config->>'free_shipping_from')::numeric,0)>0 AND sub>=(s.config->>'free_shipping_from')::numeric THEN freight:=0; END IF;
 ELSE RAISE EXCEPTION 'Entrega inválida'; END IF;
 INSERT INTO public.partner_store_orders(store_id,request_id,request_hash,access_hash,customer,items,subtotal,shipping_cost,total,fulfillment,payment_method,source,payment_status)
 VALUES(s.id,p_request,p_request_hash,p_access_hash,p_customer,lines,sub,freight,sub+freight,p_fulfillment,p_method,p_source,CASE WHEN p_source='manual' THEN 'approved' ELSE 'pending' END) RETURNING * INTO o;
 RETURN to_jsonb(o);
END $$;

CREATE FUNCTION public.reconcile_partner_store_payment(p_store uuid,p_order uuid,p_payment text,p_status text,p_amount numeric,p_updated timestamptz) RETURNS jsonb
 LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE o public.partner_store_orders%ROWTYPE;i jsonb; BEGIN
 SELECT * INTO o FROM public.partner_store_orders WHERE id=p_order AND store_id=p_store FOR UPDATE;
 IF NOT FOUND OR o.source<>'online' OR p_amount<>o.total OR p_updated IS NULL OR p_status NOT IN('pending','in_process','approved','rejected','cancelled','refunded','charged_back') THEN RAISE EXCEPTION 'Pagamento não corresponde ao pedido'; END IF;
 IF o.payment_id IS NOT NULL AND o.payment_id<>p_payment THEN
  IF o.payment_status IN('approved','refunded','charged_back') OR p_status<>'approved' THEN RETURN to_jsonb(o); END IF;
 END IF;
 IF o.provider_updated_at IS NOT NULL AND o.provider_updated_at>p_updated THEN RETURN to_jsonb(o); END IF;
 IF o.payment_status IN('refunded','charged_back') OR (o.payment_status='approved' AND p_status NOT IN('refunded','charged_back','approved')) THEN RETURN to_jsonb(o); END IF;
 IF p_status='approved' AND o.stock_released THEN RAISE EXCEPTION 'Pagamento tardio: conferir estoque e reembolso'; END IF;
 -- Rejected card attempts do not finalize a preference; another payment may succeed.
 IF p_status IN('refunded','charged_back','cancelled') AND NOT o.stock_released THEN
  FOR i IN SELECT value FROM jsonb_array_elements(o.items) LOOP
   UPDATE public.partner_store_products SET stock=stock+(i->>'quantity')::integer WHERE id=(i->>'product_id')::uuid AND store_id=o.store_id;
  END LOOP;
 END IF;
 UPDATE public.partner_store_orders SET payment_status=p_status,payment_id=p_payment,provider_updated_at=p_updated,
  stock_released=stock_released OR p_status IN('refunded','charged_back','cancelled'),
  delivery_status=CASE WHEN p_status IN('refunded','charged_back','cancelled') THEN 'cancelado' ELSE delivery_status END
 WHERE id=o.id RETURNING * INTO o;
 RETURN to_jsonb(o);
END $$;

CREATE FUNCTION public.manage_partner_store_order(p_store uuid,p_order uuid,p_action text,p_patch jsonb) RETURNS jsonb
 LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
DECLARE o public.partner_store_orders%ROWTYPE;i jsonb; BEGIN
 SELECT * INTO o FROM public.partner_store_orders WHERE id=p_order AND store_id=p_store FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Venda não encontrada'; END IF;
 IF p_action='delete' THEN
  IF o.source<>'manual' THEN RAISE EXCEPTION 'Pedido online deve ser cancelado ou reembolsado no Mercado Pago antes de arquivar'; END IF;
  IF NOT o.stock_released THEN FOR i IN SELECT value FROM jsonb_array_elements(o.items) LOOP
   UPDATE public.partner_store_products SET stock=stock+(i->>'quantity')::integer WHERE id=(i->>'product_id')::uuid AND store_id=o.store_id;
  END LOOP; END IF;
  UPDATE public.partner_store_orders SET deleted_at=now(),delivery_status='cancelado',payment_status='cancelled',stock_released=true WHERE id=o.id RETURNING * INTO o;
 ELSIF p_action='archive' THEN
  IF o.payment_status NOT IN('refunded','charged_back','cancelled') THEN RAISE EXCEPTION 'Somente pedidos cancelados ou reembolsados podem ser arquivados'; END IF;
  UPDATE public.partner_store_orders SET deleted_at=now() WHERE id=o.id RETURNING * INTO o;
 ELSIF p_action='edit' THEN
  IF p_patch->>'delivery_status' NOT IN('preparando','enviado','entregue') OR o.payment_status<>'approved' THEN RAISE EXCEPTION 'Somente vendas pagas podem avançar na entrega'; END IF;
  UPDATE public.partner_store_orders SET delivery_status=p_patch->>'delivery_status',notes=coalesce(p_patch->>'notes',notes),
   customer=CASE WHEN source='manual' THEN coalesce(p_patch->'customer',customer) ELSE customer END WHERE id=o.id RETURNING * INTO o;
 ELSE RAISE EXCEPTION 'Operação inválida'; END IF;
 RETURN to_jsonb(o);
END $$;
