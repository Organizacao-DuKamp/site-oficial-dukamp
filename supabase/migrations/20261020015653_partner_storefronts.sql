CREATE VIEW public.partner_store_summary WITH(security_invoker=true) AS
 SELECT s.id AS store_id,
 (SELECT count(*) FROM public.partner_store_products p WHERE p.store_id=s.id AND p.deleted_at IS NULL) AS products,
 (SELECT coalesce(sum(p.stock),0) FROM public.partner_store_products p WHERE p.store_id=s.id AND p.deleted_at IS NULL) AS units,
 (SELECT count(*) FROM public.partner_store_orders o WHERE o.store_id=s.id AND o.deleted_at IS NULL) AS orders,
 (SELECT count(*) FROM public.partner_store_orders o WHERE o.store_id=s.id AND o.deleted_at IS NULL AND o.payment_status='approved') AS paid_orders,
 (SELECT coalesce(sum(o.total),0) FROM public.partner_store_orders o WHERE o.store_id=s.id AND o.deleted_at IS NULL AND o.payment_status='approved') AS revenue,
 (SELECT count(*) FROM public.partner_store_orders o WHERE o.store_id=s.id AND o.deleted_at IS NULL AND o.payment_status IN('pending','in_process','rejected')) AS pending,
 (SELECT count(*) FROM public.partner_store_visits v WHERE v.store_id=s.id AND v.day>=current_date-29) AS visits_30d
 FROM public.partner_stores s;
